"""Deterministically render Open VS Code branding from the approved icon source.

Requires Pillow. Source PNG is original approved artwork, not generated by this script.
The transparent central mark and its glow remain intact.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "icon-source-cyberpunk.png"
SIZES = {48: "icon-48.png", 128: "icon-128.png", 256: "icon.png", 512: "icon-512.png"}


def icon_frame(src: Image.Image) -> Image.Image:
    src = src.convert("RGBA")
    alpha = src.getchannel("A")
    # Disregard near-invisible stray pixels when selecting composition bounds.
    visible = alpha.point(lambda value: 255 if value >= 5 else 0)
    bbox = visible.getbbox()
    if bbox is None:
        raise ValueError("Icon source has no visible pixels")
    left, top, right, bottom = bbox
    w, h = right - left, bottom - top
    edge = max(w, h)
    margin = round(edge * 0.075)
    canvas_size = edge + margin * 2
    out = Image.new("RGBA", (canvas_size, canvas_size), (0, 0, 0, 0))
    cx = (left + right) / 2
    cy = (top + bottom) / 2
    x = round(canvas_size / 2 - cx)
    y = round(canvas_size / 2 - cy)
    out.paste(src, (x, y))
    return out


def main() -> None:
    if not SOURCE.is_file():
        raise FileNotFoundError(f"Missing source artwork: {SOURCE}")
    with Image.open(SOURCE) as image:
        framed = icon_frame(image)
        for size, name in SIZES.items():
            framed.resize((size, size), Image.Resampling.LANCZOS).save(ROOT / name, optimize=True)


if __name__ == "__main__":
    main()
