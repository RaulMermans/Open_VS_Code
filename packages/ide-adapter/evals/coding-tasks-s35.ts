function oracle(body: string, opts: { typecheck?: boolean } = {}): CodingTask["oracle"] {
  return {
    kind: "node",
    script: [
      "import { readFileSync } from 'node:fs'",
      "import { execFileSync } from 'node:child_process'",
      "const fail = (m) => { console.log(m); process.exit(1) }",
      "const src = (f) => readFileSync('WS/' + f, 'utf8')",
      "const has = (f, w) => new RegExp('(?<![\\\\w$])' + w + '(?![\\\\w$])').test(src(f))",
      "const throwsRange = (fn) => { try { fn() } catch (e) { return e instanceof RangeError } return false }",
      ...(opts.typecheck ? [`try { execFileSync(process.execPath, [${JSON.stringify(TSC)}, '--noEmit', '-p', 'WS/tsconfig.json'], { stdio: 'pipe' }) } catch (e) { fail('typecheck: ' + String(e.stdout).slice(0, 400)) }`] : []),
      body,
    ].join("\n") + "\n",
  }
}

